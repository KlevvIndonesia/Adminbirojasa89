/**
 * Phase 1 — Core Financial Security Integration & Regression Tests
 * Admin SUN89 — Biro Jasa Management System
 * 
 * Verifies:
 * 1. DEF-FIN-001: Void unverified payment must not create false cash outflow.
 * 2. DEF-FIN-001: Void verified payment creates exactly one corresponding reversal.
 * 3. DEF-FIN-001: Duplicate void request is prevented.
 * 4. DEF-FIN-002: Messenger-to-office transfer eliminated from external inflow.
 * 5. DEF-FIN-002: Office-to-messenger transfer eliminated from external outflow.
 * 6. DEF-FIN-002: Genuine customer payments remain classified as external inflow.
 * 7. DEF-FIN-002: Genuine operational expenses remain classified as external outflow.
 * 8. DEF-FIN-002: P&L canonical calculations remain consistent and exclude internal transfers.
 */

import test from "node:test";
import assert from "node:assert";
import { db } from "../server/src/database/db";
import { orderService } from "../server/src/services/orderService";
import { financeService } from "../server/src/services/financeService";
import { dbFinanceRepository } from "../server/src/repositories/dbFinanceRepository";
import {
  computeCashFlowReconciliation,
  computeCanonicalLabaRugi,
  isInternalTransferTransaction,
} from "../src/domain/finance/labaRugiCanonical";

const testAdmin: any = {
  userId: "usr-admin-1",
  nama: "Admin Operasional",
  role: "administrator",
  jabatan: "ADMIN",
  email: "admin@test.local",
};

const testSupervisor: any = {
  userId: "usr-spv-1",
  nama: "Supervisor Utama",
  role: "supervisor",
  jabatan: "SVP",
  email: "spv@test.local",
};

test("PHASE 1 CORE FINANCIAL SECURITY TEST SUITE", async (suite) => {

  // ═══════════════════════════════════════════════════════════════════════════════
  // TASK 2: INTERNAL CASH TRANSFER ELIMINATION (DEF-FIN-002)
  // ═══════════════════════════════════════════════════════════════════════════════

  await suite.test("2.1: isInternalTransferTransaction correctly identifies all canonical transfer forms", () => {
    // Structured category/jenis
    assert.strictEqual(isInternalTransferTransaction({ kategori: "Transfer" }), true);
    assert.strictEqual(isInternalTransferTransaction({ jenis: "Transfer" }), true);

    // Canonical descriptions generated by transferMessengerToOffice and transferOfficeToMessenger
    assert.strictEqual(
      isInternalTransferTransaction({
        keterangan: "[SETORAN KURIR] Penerimaan Sisa Kas Messenger: Budi Santoso [Ref: TRF-M2O-12345]",
      }),
      true
    );
    assert.strictEqual(
      isInternalTransferTransaction({
        keterangan: "[PANJAR KURIR] Penyerahan Kas Operasional / Uang Jalan ke: Budi Santoso [Ref: TRF-O2M-12345]",
      }),
      true
    );
    assert.strictEqual(
      isInternalTransferTransaction({
        keterangan: "[PANJAR DITERIMA] Penerimaan Kas Operasional / Uang Jalan dari Kantor [Ref: TRF-O2M-12345]",
      }),
      true
    );
    assert.strictEqual(
      isInternalTransferTransaction({
        keterangan: "[SETORAN] Setor Sisa Kas Messenger ke Kantor [Ref: TRF-M2O-12345]",
      }),
      true
    );

    // Negative tests: genuine receipts and expenses must NOT match
    assert.strictEqual(
      isInternalTransferTransaction({
        keterangan: "Pembayaran: INV-1026-001 - PT Sinar Abadi (B 1234 ABC / BCA)",
        status: "Debit",
      }),
      false
    );
    assert.strictEqual(
      isInternalTransferTransaction({
        keterangan: "Bensin operasional jemput berkas di Jakarta Barat",
        kategori: "Bensin",
      }),
      false
    );
    assert.strictEqual(
      isInternalTransferTransaction({
        keterangan: "Pembayaran Listrik Kantor Bulan November 2026",
        kategori: "Operasional Kantor",
      }),
      false
    );
  });

  await suite.test("2.2: Messenger-to-office transfer is eliminated from external inflow", () => {
    const kasKantorSetoran = {
      id: 101,
      tanggal: "2026-11-04",
      keterangan: "[SETORAN KURIR] Penerimaan Sisa Kas Messenger: Ahmad [Ref: TRF-M2O-001]",
      status: "Debit" as const,
      debit: 500000,
      kredit: 0,
      saldo: 15500000,
      kategori: "Transfer",
    };

    const kasMessengerSetoran = {
      id: 201,
      tanggal: "2026-11-04",
      jenis: "Transfer",
      messenger: "Ahmad",
      keterangan: "[SETORAN] Setor Sisa Kas Messenger ke Kantor [Ref: TRF-M2O-001]",
      in: 0,
      out: 500000,
      total: 0,
      kategori: "Transfer",
    };

    const rekon = computeCashFlowReconciliation([kasKantorSetoran], [kasMessengerSetoran], "monthly");

    // Internal transfer eliminated
    assert.strictEqual(rekon.rekapitulasiGabungan.internalTransferEliminated.messengerToOffice, 500000);
    assert.strictEqual(rekon.rekapitulasiGabungan.internalTransferEliminated.total, 500000);

    // External revenue must NOT increase (must be Rp 0)
    assert.strictEqual(rekon.rekapitulasiGabungan.totalPenerimaanEksternal, 0);
    assert.strictEqual(rekon.rekapitulasiGabungan.rincianPenerimaan.tagihanPelanggan, 0);
    assert.strictEqual(rekon.rekapitulasiGabungan.totalPengeluaranEksternal, 0);
  });

  await suite.test("2.3: Office-to-messenger transfer (panjar) is eliminated from external outflow", () => {
    const kasKantorPanjar = {
      id: 102,
      tanggal: "2026-11-04",
      keterangan: "[PANJAR KURIR] Penyerahan Kas Operasional / Uang Jalan ke: Ahmad [Ref: TRF-O2M-001]",
      status: "Kredit" as const,
      debit: 0,
      kredit: 1000000,
      saldo: 14000000,
      kategori: "Transfer",
    };

    const kasMessengerPanjar = {
      id: 202,
      tanggal: "2026-11-04",
      jenis: "Transfer",
      messenger: "Ahmad",
      keterangan: "[PANJAR DITERIMA] Penerimaan Kas Operasional / Uang Jalan dari Kantor [Ref: TRF-O2M-001]",
      in: 1000000,
      out: 0,
      total: 1000000,
      kategori: "Transfer",
    };

    const rekon = computeCashFlowReconciliation([kasKantorPanjar], [kasMessengerPanjar], "monthly");

    // Internal transfer eliminated
    assert.strictEqual(rekon.rekapitulasiGabungan.internalTransferEliminated.officeToMessenger, 1000000);
    assert.strictEqual(rekon.rekapitulasiGabungan.internalTransferEliminated.total, 1000000);

    // External expenses must NOT increase (must be Rp 0)
    assert.strictEqual(rekon.rekapitulasiGabungan.totalPengeluaranEksternal, 0);
    assert.strictEqual(rekon.rekapitulasiGabungan.rincianPengeluaran.operasionalKantor, 0);
    assert.strictEqual(rekon.rekapitulasiGabungan.totalPenerimaanEksternal, 0);
  });

  await suite.test("2.4: Genuine customer receipt and operational expense are preserved", () => {
    const kasCustomer = {
      id: 103,
      tanggal: "2026-11-04",
      keterangan: "Pembayaran: INV-1026-999 - PT Maju Jaya (B 9999 XYZ / Kas Kantor)",
      status: "Debit" as const,
      debit: 2500000,
      kredit: 0,
      saldo: 17500000,
    };

    const kasOpex = {
      id: 104,
      tanggal: "2026-11-04",
      keterangan: "Pembayaran Tagihan Listrik & Internet Kantor",
      status: "Kredit" as const,
      debit: 0,
      kredit: 450000,
      saldo: 17050000,
      kategori: "Operasional Kantor",
    };

    const rekon = computeCashFlowReconciliation([kasCustomer, kasOpex], [], "monthly");

    assert.strictEqual(rekon.rekapitulasiGabungan.totalPenerimaanEksternal, 2500000);
    assert.strictEqual(rekon.rekapitulasiGabungan.rincianPenerimaan.tagihanPelanggan, 2500000);
    assert.strictEqual(rekon.rekapitulasiGabungan.totalPengeluaranEksternal, 450000);
    assert.strictEqual(rekon.rekapitulasiGabungan.rincianPengeluaran.operasionalKantor, 450000);
    assert.strictEqual(rekon.rekapitulasiGabungan.perubahanKasBersih, 2050000);
    assert.strictEqual(rekon.rekapitulasiGabungan.internalTransferEliminated.total, 0);
  });

  await suite.test("2.5: Canonical P&L strictly excludes internal transfers from OPEX", () => {
    const kasTransfers = [
      {
        id: 105,
        tanggal: "2026-11-04",
        keterangan: "[PANJAR KURIR] Penyerahan Kas Operasional / Uang Jalan ke: Ahmad [Ref: TRF-O2M-002]",
        status: "Kredit" as const,
        debit: 0,
        kredit: 750000,
        saldo: 10000000,
        kategori: "Transfer",
      },
    ];

    const pnl = computeCanonicalLabaRugi([], [], [], "monthly", undefined, undefined, undefined, kasTransfers);

    // Panjar transfer must have Rp 0 impact on P&L operating expense
    assert.strictEqual(pnl.pengeluaranKantor, 0);
    assert.strictEqual(pnl.totalBebanOperasional, 0);
  });

  // ═══════════════════════════════════════════════════════════════════════════════
  // TASK 1: VOID UNVERIFIED VS VERIFIED PAYMENT (DEF-FIN-001)
  // ═══════════════════════════════════════════════════════════════════════════════

  await suite.test("1.1: Void unverified payment must NOT create Kas Kantor cash outflow", () => {
    // 1. Create a dummy order and invoice
    const order = orderService.createOrder({
      customer: "Customer Unverified Test",
      nomorHP: "081211110091",
      layanan: "Perpanjangan STNK",
      nopol: "B 1234 UNV",
      biayaJasa: 300000,
      totalEstimasi: 1000000,
      biayaSamsat: 700000,
      payment: {
        tipePembayaran: "Bayar di Awal",
        metodePembayaran: "Transfer Bank",
        totalBiaya: 1000000,
        dibayar: 0,
      },
    }, testAdmin);

    const inv = dbFinanceRepository.getInvoiceByOrderNo(order.orderNo)!;
    assert.ok(inv, "Invoice must exist");

    // 2. Record an unverified payment directly
    const payRes = dbFinanceRepository.recordInvoicePayment({
      invoiceNo: inv.invoiceNo,
      orderNo: order.orderNo,
      nominal: 1000000,
      metodePembayaran: "Transfer Bank",
      namaBank: "BCA",
      tanggalBayar: "2026-11-04",
      statusVerifikasi: "MENUNGGU_VERIFIKASI",
      kasKantorId: undefined, // No Kas Kantor entry!
      catatan: "Draft transfer pending verification",
    });

    const paymentId = payRes.id;
    const initialPayment = dbFinanceRepository.getInvoicePaymentById(paymentId);
    assert.strictEqual(initialPayment.status_verifikasi, "MENUNGGU_VERIFIKASI");
    assert.strictEqual(initialPayment.kas_kantor_id, null);

    // 3. Measure Kas Kantor row count and balance before void
    const kasBefore = db.prepare("SELECT COUNT(*) as count, COALESCE(SUM(debit), 0) - COALESCE(SUM(kredit), 0) as balance FROM kas_kantor").get() as any;

    // 4. Supervisor voids this unverified payment
    const voidResult = financeService.voidInvoicePayment(
      inv.id,
      paymentId,
      "Bukti transfer palsu setelah diperiksa ke rekening koran",
      testSupervisor
    );

    // 5. Measure Kas Kantor row count and balance after void
    const kasAfter = db.prepare("SELECT COUNT(*) as count, COALESCE(SUM(debit), 0) - COALESCE(SUM(kredit), 0) as balance FROM kas_kantor").get() as any;

    // Critical assertion: NO new rows and NO change in Kas Kantor balance!
    assert.strictEqual(kasAfter.count, kasBefore.count, "Kas Kantor must not have new rows when voiding unverified payment");
    assert.strictEqual(kasAfter.balance, kasBefore.balance, "Kas Kantor balance must remain identical (no false cash outflow)");

    // 6. Verify payment record is marked VOID with null reversal_kas_id
    const updatedPayment = dbFinanceRepository.getInvoicePaymentById(paymentId);
    assert.strictEqual(updatedPayment.is_void, 1);
    assert.strictEqual(updatedPayment.status_verifikasi, "VOID");
    assert.strictEqual(updatedPayment.reversal_kas_id, null);
    assert.strictEqual(updatedPayment.void_reason, "Bukti transfer palsu setelah diperiksa ke rekening koran");

    // 7. Invoice totals remain 0 paid and 1,000,000 sisa
    assert.strictEqual(voidResult.dibayar, 0);
    assert.strictEqual(voidResult.sisa, 1000000);
    assert.strictEqual(voidResult.status, "UNPAID");
  });

  await suite.test("1.2: Void verified payment creates exactly one reversal corresponding to original journal", () => {
    // 1. Create a dummy order and invoice
    const order = orderService.createOrder({
      customer: "Customer Verified Test",
      nomorHP: "081211110092",
      layanan: "Perpanjangan STNK",
      nopol: "B 1234 VRF",
      biayaJasa: 300000,
      totalEstimasi: 1000000,
      biayaSamsat: 700000,
      payment: {
        tipePembayaran: "Bayar di Awal",
        metodePembayaran: "Transfer Bank",
        totalBiaya: 1000000,
        dibayar: 1000000,
        buktiPembayaran: { fileName: "bukti_tf_valid.jpg", fileType: "image", uploadedAt: new Date().toISOString() },
      },
    }, testAdmin);

    const inv = dbFinanceRepository.getInvoiceByOrderNo(order.orderNo)!;
    assert.ok(inv, "Invoice must exist");

    // 2. Verify payment via orderService.verifyPayment (this adds Kas Kantor debit and links kas_kantor_id)
    orderService.verifyPayment(order.orderNo, testAdmin);

    const payments = dbFinanceRepository.getPaymentsByInvoiceNo(inv.invoiceNo);
    assert.ok(payments.length > 0, "Payment record must exist");
    const verifiedPayment = payments.find((p: any) => p.status_verifikasi === "TERVERIFIKASI" && p.kas_kantor_id != null);
    assert.ok(verifiedPayment, "Payment must be verified with kas_kantor_id");

    const paymentId = verifiedPayment.id;
    const originalKasId = verifiedPayment.kas_kantor_id;
    const originalKas = dbFinanceRepository.getKasKantorById(originalKasId)!;
    assert.strictEqual(originalKas.status, "Debit");
    assert.strictEqual(originalKas.debit, 1000000);

    const kasBefore = db.prepare("SELECT COUNT(*) as count, COALESCE(SUM(debit), 0) - COALESCE(SUM(kredit), 0) as balance FROM kas_kantor").get() as any;

    // 3. Supervisor voids this verified payment
    financeService.voidInvoicePayment(
      inv.id,
      paymentId,
      "Salah nomor rekening tujuan transfer oleh pelanggan",
      testSupervisor
    );

    // 4. Measure Kas Kantor after void
    const kasAfter = db.prepare("SELECT COUNT(*) as count, COALESCE(SUM(debit), 0) - COALESCE(SUM(kredit), 0) as balance FROM kas_kantor").get() as any;

    // Exactly one reversal row created
    assert.strictEqual(kasAfter.count, kasBefore.count + 1);
    // Balance decreased by exactly 1,000,000
    assert.strictEqual(kasAfter.balance, kasBefore.balance - 1000000);

    // Verify payment record links to the reversal journal
    const updatedPayment = dbFinanceRepository.getInvoicePaymentById(paymentId);
    assert.strictEqual(updatedPayment.is_void, 1);
    assert.strictEqual(updatedPayment.status_verifikasi, "VOID");
    assert.ok(updatedPayment.reversal_kas_id > 0);

    const reversalKas = dbFinanceRepository.getKasKantorById(updatedPayment.reversal_kas_id)!;
    assert.strictEqual(reversalKas.status, "Kredit");
    assert.strictEqual(reversalKas.kredit, 1000000);
    assert.ok(reversalKas.keterangan.includes(`[Ref: Kas #${originalKasId}]`));

    // 5. Attempt duplicate void: MUST throw 400 PAYMENT_ALREADY_VOIDED
    assert.throws(
      () => {
        financeService.voidInvoicePayment(
          inv.id,
          paymentId,
          "Mencoba void ulang pembayaran yang sama",
          testSupervisor
        );
      },
      (err: any) => {
        assert.strictEqual(err.statusCode, 400);
        assert.strictEqual(err.code, "PAYMENT_ALREADY_VOIDED");
        return true;
      }
    );

    // Ensure no additional Kas Kantor entry on duplicate void attempt
    const kasAfterDuplicate = db.prepare("SELECT COUNT(*) as count FROM kas_kantor").get() as any;
    assert.strictEqual(kasAfterDuplicate.count, kasAfter.count);
  });
});
